const fs=require('fs'),path=require('path'),assert=require('assert');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const s=html.indexOf('<section id="steps">'),e=html.indexOf('</section>',s);
const sec=html.slice(s,e);
const live=sec.indexOf('>Live walk sessions</h3>'),daily=sec.indexOf('>Daily Earn Steps Board</h3>');
const all=sec.indexOf('>Step Equity scoreboard</h3>');
assert(live>0&&daily>0&&all>0,'daily, live, and all-time boards present in Step Equity');
assert(daily<sec.indexOf('id="userDash"'),'Daily Earn Steps Board is above the dashboard');
assert(sec.indexOf('id="userDash"')<live,'Your dashboard sits above Live walk sessions');
assert(live<all,'All-time Step Equity scoreboard sits after Live walk sessions');
assert(daily<live&&live<all,'order: Daily Earn, dashboard, Live walk sessions, then all-time board');
assert(sec.indexOf('id="dailyBoardBody"')<sec.indexOf('id="userDash"'),'daily table is above the dashboard');
assert(sec.indexOf('id="walkBoardBody"')<sec.indexOf('id="stepAllBoardBody"'),'all-time table follows the live walk table');
assert(sec.indexOf('id="dailyWalkBtn"')<daily,'walk controls stay above both boards');
assert(sec.indexOf('id="tenKBonus"')<daily,'10K card stays above the Daily Earn Steps Board');
assert(sec.includes('id="dailyStepBoard"'),'Daily Earn Steps Board is wrapped for the Drop Your Tuts look');
const allStart=sec.indexOf('id="stepAllBoardTitle"');
assert(allStart>0&&!sec.slice(allStart).includes('id="dailyStepBoard"'),'all-time board is not in the Drop Your Tuts cabinet');
assert(sec.includes('<th>#</th><th>Player</th><th>Total steps</th>'),'all-time columns are #, Player, Total steps');
assert(sec.includes('<th>#</th><th>Player</th><th>Steps</th>'),'daily board columns are #, Player, Steps');
console.log('PASS step-equity layout (12 checks)');
